/**
 * PI-Desktop 面板构建脚本（esbuild）。
 *
 * 为什么不用 vite：宿主用 file:// 协议加载面板，module script 会被
 * Chromium CORS 阻止；vite 的 IIFE 输出在运行时触发 React #299 崩溃
 * （最小复现已验证），而 esbuild 的 IIFE 输出在 file:// 下完全正常。
 *
 * 产物：
 *   renderer/index.html      静态入口（普通 <script>/<link>，非 module）
 *   renderer/assets/app.js   IIFE 单文件（React + Toast UI + Prism 全部语言）
 *   renderer/assets/app.css  合并样式（Tailwind + Toast UI + KaTeX + Prism 主题）
 */
import { build } from "esbuild";
import { promises as fs } from "node:fs";
import path from "node:path";
import postcss from "postcss";
import tailwindcss from "tailwindcss";
import autoprefixer from "autoprefixer";

const ROOT = process.cwd(); // renderer-src
const OUT_DIR = path.join(ROOT, "..", "renderer", "assets");

/* ---------- 1. 生成 Prism 全部语言的静态导入（按依赖拓扑序） ---------- */
const PRISM_DIR = path.join(ROOT, "node_modules", "prismjs", "components");
const CORE = ["markup", "css", "clike", "javascript", "markup-templating"];

const components = JSON.parse(
  await fs.readFile(path.join(PRISM_DIR, "..", "components.json"), "utf8"),
);
const langMap = components.languages || {};

const files = (await fs.readdir(PRISM_DIR)).filter(
  (f) =>
    f.startsWith("prism-") &&
    f.endsWith(".js") &&
    !f.endsWith(".min.js") &&
    f !== "prism-core.js" &&
    f !== "index.js",
);
const fileSet = new Set(files);

// 拓扑排序：依赖先于使用方（DFS 后序），核心语言固定在前
const order = [];
const visited = new Set();
function visit(name) {
  if (visited.has(name) || !langMap[name]) return;
  visited.add(name);
  const def = langMap[name];
  const reqs = def.require
    ? Array.isArray(def.require)
      ? def.require
      : [def.require]
    : [];
  for (const r of reqs) visit(r);
  if (fileSet.has(`prism-${name}.js`)) order.push(name);
}
for (const c of CORE) visit(c);
for (const name of Object.keys(langMap).sort()) visit(name);

const gen =
  "// AUTO-GENERATED by build.mjs — do not edit\n" +
  order.map((name) => `import "prismjs/components/prism-${name}.js";`).join("\n") +
  "\n";
const genDir = path.join(ROOT, "src", "generated");
await fs.mkdir(genDir, { recursive: true });
await fs.writeFile(path.join(genDir, "prism-imports.ts"), gen, "utf8");
console.log(`[build] generated ${order.length} prism language imports (topo order)`);

/* ---------- 2. Tailwind CSS 处理插件（仅 src/index.css） ---------- */
const tailwindPlugin = {
  name: "pi-markdown-tailwind",
  setup(build) {
    build.onLoad({ filter: /src[\\/]index\.css$/ }, async (args) => {
      const source = await fs.readFile(args.path, "utf8");
      const result = await postcss([tailwindcss, autoprefixer]).process(
        source,
        { from: args.path },
      );
      return { contents: result.css, loader: "css" };
    });
  },
};

/* ---------- 3. esbuild 打包 ---------- */
await fs.mkdir(OUT_DIR, { recursive: true });
await build({
  entryPoints: [path.join(ROOT, "src", "main.tsx")],
  bundle: true,
  format: "iife",
  outfile: path.join(OUT_DIR, "app.js"),
  jsx: "automatic",
  define: { "process.env.NODE_ENV": '"production"' },
  // 字体等资源内联为 data URL：file:// 下可加载、导出 HTML 自包含
  loader: {
    ".woff2": "dataurl",
    ".woff": "dataurl",
    ".ttf": "dataurl",
    ".eot": "dataurl",
    ".otf": "dataurl",
    ".svg": "dataurl",
    ".png": "dataurl",
  },
  plugins: [tailwindPlugin],
  logLevel: "info",
  metafile: false,
});
console.log("[build] done");
