/**
 * PI-Desktop 面板构建脚本（esbuild）。
 *
 * 为什么不用 vite：宿主用 file:// 协议加载面板，module script 会被
 * Chromium CORS 阻止；vite 的 IIFE 输出在运行时触发 React #299 崩溃
 * （最小复现已验证），而 esbuild 的 IIFE 输出在 file:// 下完全正常。
 *
 * 产物：
 *   renderer/index.html      静态入口（普通 <script>/<link>，非 module）
 *   renderer/assets/app.js   IIFE 单文件（React + Milkdown/Crepe + Prism 全部语言）
 *   renderer/assets/app.css  合并样式（Tailwind + Milkdown/Crepe + KaTeX + Prism 主题）
 */
import { build } from "esbuild";
import { promises as fs } from "node:fs";
import path from "node:path";
import postcss from "postcss";
import tailwindcss from "tailwindcss";
import autoprefixer from "autoprefixer";

const ROOT = process.cwd(); // renderer-src
const OUT_DIR = path.join(ROOT, "..", "renderer", "assets");

/* ---------- 1. 生成 refractor（Prism）全部语言的静态注册模块 ---------- */
// Milkdown 的 @milkdown/plugin-prism 使用 refractor；refractor 5 的语言模块
// 自包含（内部 Prism.register 依赖），全部注册即可。
//
// 注意：单个语言模块的注册必须容错——个别语言（如 js-templates）在浏览器
// 环境下注册会抛错，若中断整个注册循环会把编辑器一起拖垮。这里逐语言
// try/catch 并继续，失败的语言仅跳过（prism 高亮侧对未注册语言本就跳过）。
const REFRACTOR_DIR = path.join(ROOT, "node_modules", "refractor", "lang");
const langNames = (await fs.readdir(REFRACTOR_DIR))
  .filter((f) => f.endsWith(".js") && f !== "index.js")
  .map((f) => f.replace(/\.js$/, ""))
  .sort();

const gen =
  "// AUTO-GENERATED by build.mjs — do not edit\n" +
  `// 全部 refractor（Prism）语言注册，共 ${langNames.length} 种，随包离线可用\n` +
  langNames
    .map((name, i) => `import lang_${i} from "refractor/${name}";`)
    .join("\n") +
  "\n\n" +
  "const FAILED = new Set<string>();\n" +
  "export function registerRefractorLanguages(\n" +
  "  refractor: { register(lang: unknown): void },\n" +
  "): void {\n" +
  langNames
    .map(
      (name, i) =>
        `  try { refractor.register(lang_${i}); } catch { FAILED.add(${JSON.stringify(name)}); }`,
    )
    .join("\n") +
  "\n  if (FAILED.size) {\n" +
  '    console.warn("[pi-markdown] 以下 Prism 语言注册失败（已跳过）:", [...FAILED].join(", "));\n' +
  "  }\n" +
  "}\n";
const genDir = path.join(ROOT, "src", "generated");
await fs.mkdir(genDir, { recursive: true });
await fs.writeFile(path.join(genDir, "refractor-imports.ts"), gen, "utf8");
console.log(`[build] generated ${langNames.length} refractor language registrations`);

/* ---------- 2. Tailwind CSS 处理插件（仅 src/index.css） ---------- */
const tailwindPlugin = {
  name: "pi-markdown-tailwind",
  setup(build) {
    build.onLoad({ filter: /src[\\/]index\.css$/ }, async (args) => {
      const source = await fs.readFile(args.path, "utf8");
      const result = await postcss([tailwindcss, autoprefixer]).process(
        source,
        { from: args.path },
      );
      return { contents: result.css, loader: "css" };
    });
  },
};

/* ---------- 3. esbuild 打包 ---------- */
await fs.mkdir(OUT_DIR, { recursive: true });
await build({
  entryPoints: [path.join(ROOT, "src", "main.tsx")],
  bundle: true,
  format: "iife",
  outfile: path.join(OUT_DIR, "app.js"),
  jsx: "automatic",
  define: { "process.env.NODE_ENV": '"production"' },
  // 字体等资源内联为 data URL：file:// 下可加载、导出 HTML 自包含
  loader: {
    ".woff2": "dataurl",
    ".woff": "dataurl",
    ".ttf": "dataurl",
    ".eot": "dataurl",
    ".otf": "dataurl",
    ".svg": "dataurl",
    ".png": "dataurl",
  },
  plugins: [tailwindPlugin],
  logLevel: "info",
  metafile: false,
});
console.log("[build] done");
